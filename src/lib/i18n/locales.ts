export const DICTS: Record<LangCode, Dict> = { en, zh, es, fr, ar, ja, de, ko, pt, it, hi, ru, tr };

export function translate(lang: LangCode, key: string, vars?: Record<string, string>) {
  const dict = (key.startsWith("bot.") ? BOT_DICTS[lang] : DICTS[lang]) as Record<string, string>;
  const fallback = (key.startsWith("bot.") ? BOT_DICTS.en : en) as Record<string, string>;
  let text = dict[key] ?? fallback[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  return text;
}
